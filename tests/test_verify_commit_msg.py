import importlib.util
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCRIPT_PATH = ROOT / ".github" / "scripts" / "verify-commit-msg.py"

SPEC = importlib.util.spec_from_file_location("verify_commit_msg", SCRIPT_PATH)
assert SPEC and SPEC.loader
verify_commit_msg = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(verify_commit_msg)


class VerifyCommitMsgTests(unittest.TestCase):
    def test_valid_conventional_commits_and_bypasses_pass(self):
        self.assertEqual(verify_commit_msg.validate_commit_message("feat(ci): add workflow hygiene gate"), [])
        self.assertEqual(verify_commit_msg.validate_commit_message("Merge pull request #12 from org/branch"), [])
        self.assertEqual(verify_commit_msg.validate_commit_message('Revert "feat: demo"'), [])

    def test_rejects_bad_prefix_long_subject_period_buzzword_watermark_and_dashes(self):
        self.assertTrue(verify_commit_msg.validate_commit_message("updated things"))
        self.assertTrue(verify_commit_msg.validate_commit_message("feat(ci): " + "x" * 70))
        self.assertTrue(verify_commit_msg.validate_commit_message("fix(ci): handle empty diff."))
        self.assertTrue(verify_commit_msg.validate_commit_message("feat(ci): add check\n\nThis is a robust paradigm."))
        self.assertTrue(verify_commit_msg.validate_commit_message("feat(ci): add check\n\nGenerated by Claude"))
        self.assertTrue(verify_commit_msg.validate_commit_message("feat(ci): add check \u2014 details"))

    def test_merge_and_revert_still_enforce_body_anti_slop_and_dash_checks(self):
        self.assertEqual(
            verify_commit_msg.validate_commit_message("Merge pull request #12 from org/branch\n\nClean merge summary."),
            [],
        )
        self.assertTrue(
            verify_commit_msg.validate_commit_message(
                "Merge pull request #1 from x/y\n\nGenerated by Claude \u2014 seamless paradigm"
            )
        )
        self.assertTrue(
            verify_commit_msg.validate_commit_message("Merge branch 'main'\n\nThis is a robust update.")
        )
        self.assertTrue(
            verify_commit_msg.validate_commit_message('Revert "feat: demo"\n\ndetails \u2014 explanation')
        )


if __name__ == "__main__":
    unittest.main()
