    def test_self_scan_of_dotgithub_repo_passes_cleanly(self):
        rc = audit_ai_smells.main(["--repo-root", str(ROOT), "--all"])
        self.assertEqual(rc, 0)

    def test_baseline_count_zero_and_invalid_count_rejected(self):
        finding = {"file": "src/A.cs", "line": 1, "ruleId": "EMPTY_CATCH", "fingerprint": "catch {}", "message": "m"}
        baselined, unapproved = audit_ai_smells.apply_baseline([finding], [{**finding, "count": 0}])
        self.assertEqual(baselined, [])
        self.assertEqual(len(unapproved), 1)
        for bad_count in ("999", -1, 1.5, True):
            with self.subTest(bad_count=bad_count):
                with self.assertRaises(ValueError):
                    audit_ai_smells.apply_baseline([finding], [{**finding, "count": bad_count}])

    def test_inline_style_rejects_piggybacked_css_and_allows_valid_multi_decl(self):
        bad_html = (
            '<div style="position: fixed; color: red; background-image: none;"></div>\n'
            '<div style="width: 100px; color: @themeColor;"></div>\n'
            '<div style=""></div>\n'
        )
        findings = audit_ai_smells.audit_content(bad_html, "Components/Piggyback.razor")
        self.assertEqual([f["ruleId"] for f in findings], ["INLINE_STYLE", "INLINE_STYLE", "INLINE_STYLE"])

        good_html = '<div style="background-image: url(\'data:image/svg+xml;utf8,x\'); width: @pct%;"></div>\n'
        self.assertEqual(audit_ai_smells.audit_content(good_html, "Components/Clean.razor"), [])

