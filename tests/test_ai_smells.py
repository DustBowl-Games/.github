import contextlib
import importlib.util
import io
import json
import pathlib
import subprocess
import tempfile
import unittest
from unittest import mock

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCRIPT_PATH = ROOT / ".github" / "scripts" / "audit-ai-smells.py"

SPEC = importlib.util.spec_from_file_location("audit_ai_smells", SCRIPT_PATH)
assert SPEC and SPEC.loader
audit_ai_smells = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(audit_ai_smells)


class AuditAiSmellsTests(unittest.TestCase):
    def test_clean_code_grounded_todo_dynamic_style_and_pep8_spacing_pass(self):
        cs_sample = "\n".join([
            "// TODO(#2451): replace legacy endpoint after migration",
            "try {",
            "    DoWork();",
            "} catch (Exception ex) {",
            "    _logger.LogError(ex, \"Failed\");",
            "}",
        ])
        self.assertEqual(audit_ai_smells.audit_content(cs_sample, "Services/Worker.cs"), [])

        razor_sample = (
            '<div class="hero" style="background-image: url(\'/img/bg.webp\');"></div>\n'
            '<div class="bar" style="width: @percent%;"></div>\n'
        )
        self.assertEqual(audit_ai_smells.audit_content(razor_sample, "Components/Card.razor"), [])

        py_sample = "def a():\n    return 1\n\n\ndef b():\n    return 2\n"
        self.assertEqual(audit_ai_smells.audit_content(py_sample, "scripts/helper.py"), [])

    def test_markdown_dashes_allowed_only_when_flag_enabled(self):
        md = "Infrastructure note \u2014 details.\n"
        self.assertEqual(
            [f["ruleId"] for f in audit_ai_smells.audit_content(md, "docs/guide.md", allow_markdown_dashes=False)],
            ["DISALLOWED_DASH"],
        )
        self.assertEqual(
            audit_ai_smells.audit_content(md, "docs/guide.md", allow_markdown_dashes=True),
            [],
        )
        # Code/YAML still bans dashes even when allow_markdown_dashes=True
        code = "const note = 'bad \u2013 dash';\n"
        self.assertEqual(
            [f["ruleId"] for f in audit_ai_smells.audit_content(code, "src/app.js", allow_markdown_dashes=True)],
            ["DISALLOWED_DASH"],
        )

    def test_detects_ai_chatter_watermark_buzzwords_and_ungrounded_stubs(self):
        bad = "\n".join([
            "// Here is the updated handler for your service",
            "// Generated by Claude",
            "// This leverages a robust, seamless paradigm",
            "// TODO: clean this up later",
            "throw new NotImplementedException();",
            'string copy = "Lorem ipsum dolor sit amet";',
        ])
        findings = audit_ai_smells.audit_content(bad, "Services/Demo.cs")
        rules = [f["ruleId"] for f in findings]
        self.assertIn("AI_NARRATION_CHATTER", rules)
        self.assertIn("AI_WATERMARK", rules)
        self.assertIn("AI_BUZZWORD", rules)
        self.assertEqual(rules.count("UNGROUNDED_STUB"), 3)

    def test_detects_empty_catch_empty_helper_and_static_inline_style(self):
        cs_bad = "public static class EmptyHelpers {\n}\ntry {\n  Run();\n} catch (Exception ex) {\n}\n"
        rules_cs = {f["ruleId"] for f in audit_ai_smells.audit_content(cs_bad, "Services/Helpers.cs")}
        self.assertIn("EMPTY_CATCH", rules_cs)
        self.assertIn("EMPTY_HELPER", rules_cs)

        html_bad = '<div style="margin-top: 24px;">Bad</div>\n'
        rules_html = {f["ruleId"] for f in audit_ai_smells.audit_content(html_bad, "Components/Bad.razor")}
        self.assertEqual(rules_html, {"INLINE_STYLE"})

    def test_detects_trailing_whitespace_and_excessive_blank_lines(self):
        py_bad = "x = 1   \n\n\n\ny = 2\n"
        rules_py = {f["ruleId"] for f in audit_ai_smells.audit_content(py_bad, "scripts/bad.py")}
        self.assertEqual(rules_py, {"TRAILING_WHITESPACE", "EXCESSIVE_BLANK_LINES"})

        yml_bad = "name: test\n\n\njobs: {}\n"
        rules_yml = {f["ruleId"] for f in audit_ai_smells.audit_content(yml_bad, ".github/workflows/x.yml")}
        self.assertEqual(rules_yml, {"EXCESSIVE_BLANK_LINES"})

    def test_diff_mode_only_flags_added_lines_and_respects_baseline_counts(self):
        diff = "\n".join([
            "+++ b/Services/Foo.cs",
            "@@ -10,0 +10,2 @@",
            "+// TODO: ungrounded 1",
            "+// TODO: ungrounded 1",
        ])
        findings = audit_ai_smells.audit_diff_text(diff)
        self.assertEqual(len(findings), 2)

        baseline = [{"file": "Services/Foo.cs", "ruleId": "UNGROUNDED_STUB", "fingerprint": "// TODO: ungrounded 1", "count": 1}]
        baselined, unapproved = audit_ai_smells.apply_baseline(findings, baseline)
        self.assertEqual(len(baselined), 1)
        self.assertEqual(len(unapproved), 1)

    def test_generated_baseline_json_is_exempt_in_full_and_diff_modes_while_new_code_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp)
            subprocess.run(["git", "init", "-b", "main"], cwd=repo, check=True, capture_output=True)
            subprocess.run(["git", "config", "user.email", "ci@dustbowl.games"], cwd=repo, check=True, capture_output=True)
            subprocess.run(["git", "config", "user.name", "DustBowl CI"], cwd=repo, check=True, capture_output=True)

            legacy_cs = repo / "Services" / "Legacy.cs"
            legacy_cs.parent.mkdir(parents=True)
            legacy_cs.write_text(
                "// TODO: old ungrounded\n"
                "// seamless migration\n"
                "// note \u2014 legacy dash\n",
                encoding="utf-8",
            )
            subprocess.run(["git", "add", "."], cwd=repo, check=True, capture_output=True)
            subprocess.run(["git", "commit", "-m", "chore: legacy code"], cwd=repo, check=True, capture_output=True)
            base_sha = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=repo, check=True, capture_output=True, text=True
            ).stdout.strip()

            buf = io.StringIO()
            with contextlib.redirect_stdout(buf):
                rc_print = audit_ai_smells.main(["--repo-root", str(repo), "--print-baseline"])
            self.assertEqual(rc_print, 0)
            baseline_json = buf.getvalue()
            self.assertNotIn("\u2014", baseline_json)
            parsed = json.loads(baseline_json)
            self.assertGreaterEqual(len(parsed["ai_smells_baseline"]), 3)

            baseline_file = repo / "config" / "ai-smells-baseline.json"
            baseline_file.parent.mkdir(parents=True)
            baseline_file.write_text(baseline_json, encoding="utf-8")

            subprocess.run(["git", "add", "."], cwd=repo, check=True, capture_output=True)
            subprocess.run(["git", "commit", "-m", "chore: add baseline"], cwd=repo, check=True, capture_output=True)
            head_sha = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=repo, check=True, capture_output=True, text=True
            ).stdout.strip()

            # Full scan with baseline passes
            rc_all = audit_ai_smells.main([
                "--repo-root", str(repo),
                "--all",
                "--baseline", "config/ai-smells-baseline.json",
            ])
            self.assertEqual(rc_all, 0)

            # Diff mode adding config/ai-smells-baseline.json passes
            rc_diff = audit_ai_smells.main([
                "--repo-root", str(repo),
                "--base", base_sha,
                "--head", head_sha,
                "--baseline", "config/ai-smells-baseline.json",
            ])
            self.assertEqual(rc_diff, 0)

            # Custom --baseline path outside config/ is also exempt in both --all and diff modes
            custom_file = repo / "waivers" / "custom.json"
            custom_file.parent.mkdir(parents=True)
            custom_file.write_text(baseline_json, encoding="utf-8")
            subprocess.run(["git", "add", "."], cwd=repo, check=True, capture_output=True)
            subprocess.run(["git", "commit", "-m", "chore: add custom baseline"], cwd=repo, check=True, capture_output=True)
            custom_sha = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=repo, check=True, capture_output=True, text=True
            ).stdout.strip()

            self.assertEqual(
                audit_ai_smells.main(["--repo-root", str(repo), "--all", "--baseline", "waivers/custom.json"]),
                0,
            )
            self.assertEqual(
                audit_ai_smells.main([
                    "--repo-root", str(repo),
                    "--base", head_sha,
                    "--head", custom_sha,
                    "--baseline", "waivers/custom.json",
                ]),
                0,
            )

            # Adding a new violation in code still fails in both modes
            new_cs = repo / "Services" / "NewService.cs"
            new_cs.write_text("// seamless new code\n", encoding="utf-8")
            subprocess.run(["git", "add", "."], cwd=repo, check=True, capture_output=True)
            subprocess.run(["git", "commit", "-m", "feat: add new service"], cwd=repo, check=True, capture_output=True)
            bad_sha = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=repo, check=True, capture_output=True, text=True
            ).stdout.strip()

            rc_bad_all = audit_ai_smells.main([
                "--repo-root", str(repo),
                "--all",
                "--baseline", "waivers/custom.json",
            ])
            self.assertEqual(rc_bad_all, 1)

            rc_bad_diff = audit_ai_smells.main([
                "--repo-root", str(repo),
                "--base", custom_sha,
                "--head", bad_sha,
                "--baseline", "waivers/custom.json",
            ])
            self.assertEqual(rc_bad_diff, 1)

